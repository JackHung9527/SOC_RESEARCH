#!/usr/bin/env python3
"""sync_ch6_docx_20260707.py — 第六章定量收束版同步（就地改 _20260707.docx）。"""

import sys

sys.path.insert(0, "SCRIPTS")
from sync_ch4_docx_20260707 import set_p, insert_after, set_cell  # noqa: E402

import docx  # noqa: E402
from docx.table import Table  # noqa: E402
from docx.text.paragraph import Paragraph  # noqa: E402
from docx.oxml.ns import qn  # noqa: E402

P_ = "DOC/論文撰寫/鋰電池SOC估測方法之比較與嵌入式實作_20260707.docx"


def main():
    d = docx.Document(P_)
    ch6, in6 = [], False
    for el in d.element.body:
        if el.tag == qn("w:p"):
            p = Paragraph(el, d)
            t = p.text.strip()
            if p.style.name == "Heading 1":
                in6 = t.startswith("第六章")
            if in6:
                ch6.append(p)

    def P(prefix):
        for p in ch6:
            if p.text.strip().startswith(prefix):
                return p
        sys.exit(f"找不到段落: {prefix}")

    # ---- 6.1 ----
    p3 = P("3. 同硬體環境下的精度／資源量化比較框架")
    set_p(p3,
          "3. **同硬體環境下的精度／資源量化比較**：建立「同電池、同協定、同微控制器、同量測"
          "路徑」之公平 benchmark，並完成整輪板端實測——精度上 EKF 於 0.5C 達 RMSE 0.87%、"
          "庫倫計數穩定於 1.8–2.2%、動態阻抗單獨反推 6–10%（第四章表 4-4）；資源上量得庫倫 "
          "305 cycles／EKF 15,187 cycles／動態阻抗 432–3,117 cycles 之三階資源梯度，以及 "
          "Flash +1.5–2.3 KB 之差分佔用（表 4-6），並證明三法並行峰值僅佔每秒運算預算 0.029%"
          "（第五章表 5-1）。三法之「精度─成本權衡」首次在受控且一致的嵌入式條件下被完整定量，"
          "填補文獻少見之缺口。")
    insert_after(p3,
          "在上述框架性貢獻之外，本研究尚有一項**由公平比較直接暴露的實測發現——量測域一致性"
          "凌駕演算法選擇**（第四章 4.3.4、圖 4-5）：參數辨識域（台架負載端）與部署量測域"
          "（板端電池端子）之間約 24 mΩ 的線材／接點電阻，足以使 EKF 產生隨倍率放大的系統性"
          "偏差、並使動態阻抗對照表整組失效；而將係數改以部署域重建後，拋物線之形狀項幾乎不變、"
          "僅常數項平移。此發現指出：**「離線建表、線上查表」之跨量測鏈搬移是嵌入式 SOC 估測的"
          "隱形失效模式**，唯有在真實部署硬體上做評估才可能暴露——此即對第一章「評估環境失真」"
          "研究缺口最直接的實證回應。")

    set_p(P("此外，本研究於實作過程中亦累積並彙整"),
          "此外，本研究於實作過程中亦累積並彙整了嵌入式量測平台之工程教訓（第五章 5.4），歸納出"
          "「不信任單點、量測涵蓋須在設計階段釐清、不讓正確性依賴隱含行為」三條普適設計原則，"
          "對自建電池測試平台者具參考價值。")

    # ---- 6.2 ----
    set_p(P("綜合全研究之精度、強健性與嵌入式資源三軸結論"),
          "綜合全研究之精度、強健性與嵌入式資源三軸**實測結論**，依目標應用之約束條件，給出 "
          "SOC 估測方法選用之決策建議如表 6-1。本表為第四章 4.4.4 應用建議在全研究結論下的"
          "收束版本，各欄數值均出自同硬體實測（第四章表 4-4／4-6、第五章表 5-1）。")

    tb = None
    for t_ in d.tables:
        h = [c.text.strip() for c in t_.rows[0].cells]
        if h[:2] == ["應用約束情境", "首選方法"]:
            tb = t_
            break
    assert tb is not None, "找不到表 6-1"
    set_cell(tb.rows[0].cells[2], "理由（實測依據）")
    set_cell(tb.rows[0].cells[3], "主要代價（實測依據）")
    rows = [
        ["極低成本／極低算力（8-bit、無 FPU、Flash < 8 KB）", "庫倫計數 + 充飽自動重錨",
         "資源下界（+1.9 KB／305 cycles）；重錨實測 4/4 次消除初值偏移",
         "無自我修正；精度上限由電流量測鏈刻度決定（實測 ±2%）；初值錯誤在重錨前不收斂"],
        ["中階且需自初值錯誤恢復、長期免人工校正", "EKF（一階 RC）",
         "精度最佳（0.5C 實測 RMSE 0.87%）；錯誤初值單步拉回；即時性代價實測僅佔每秒預算 0.024%",
         "需 OCV 表與 GITT 建表實驗；Flash 代價最大（+2.3 KB）；參數辨識必須與部署量測鏈同域，"
         "否則隨倍率產生系統性偏差"],
        ["工作中即時估測、無靜置機會、實驗成本敏感", "動態阻抗（+ 庫倫內插）",
         "無須初值與靜置，首事件（≤60 s）即重估；複用既有擾動，建表成本最低",
         "單獨反推精度有限（6–10%）且中段病態；對照表對量測域高度敏感（跨域搬移實測整組失效）"],
        ["高可靠度、資源充裕、追求最佳整體表現", "三法混合（庫倫連續 + 動態阻抗離散校正 + EKF 融合）",
         "互補：庫倫連續高解析、動態阻抗無初值校正、EKF 最佳融合與恢復；並行峰值實測僅佔每秒預算 0.029%",
         "整合複雜度最高；Flash 並行實測 +4.9 KB（RAM 嚴格可加 +112 B，第五章 5.1）"],
    ]
    for i, row in enumerate(rows, start=1):
        for j, v in enumerate(row):
            set_cell(tb.rows[i].cells[j], v)

    set_p(P("表 6-1　SOC 估測方法選用決策表"),
          "表 6-1　SOC 估測方法選用決策表（全研究實測結論版）")

    # ---- 6.3 ----
    set_p(P("3. 僅做 SOC，未做 SOH"),
          "3. **僅做 SOC，未做 SOH**：依研究範圍裁切（第一章），本研究聚焦 SOC 估測，SOH 列為"
          "未來工作。雖然第五章已實測到可分離的老化訊號（40 輪約 4.7% 衰退），但尚未實作 SOH "
          "估測演算法。")
    p5 = P("5. 部分比較數值待實測回填")
    set_p(p5,
          "5. **部分驗證項目未完成**：本稿時點，(a) 強健性壓力測試之 C-rate 切換與噪聲抗性兩項"
          "尚未施測（表 4-5）；(b) 量測域修正後之複測（板端域係數之動態阻抗線上精度、電池端域 "
          "R_0 之 EKF 精度）仍在進行；(c) EKF 之 PC 重放與參數辨識使用同一份 GITT 資料"
          "（in-sample），其獨立驗證僅由整輪板端實測承擔。本研究嚴守「不虛構數據」原則，上述"
          "項目均於正文如實標註。")
    insert_after(p5,
          "6. **精度數值受量測鏈刻度差影響**：板端與台架兩條電流量測鏈存在約 +1.2% 的刻度差"
          "（第四章 4.4.1），使板端庫倫計數之 RMSE 實為「演算法＋量測鏈」之合成值。此非缺陷"
          "而是真實部署條件的一部分，但引用絕對精度數值時應知其構成。")

    # ---- 6.4 / 6.5 ----
    set_p(P("本研究之測試平台與長期循環數據"),
          "本研究之測試平台與長期循環數據（第五章：40 輪、可分離之 4.7% 老化軌跡）為 SOH 估測"
          "提供了現成基礎。未來可於現有框架上延伸：")

    set_p(P("本研究從一個務實的工程命題出發"),
          "本研究從一個務實的工程命題出發——在真實的嵌入式資源約束下，三種主流 SOC 估測方法"
          "究竟孰優孰劣？透過自建的高再現性測試平台與同硬體公平 benchmark，本研究將此問題的"
          "答案由文獻中的定性印象，推進為實測數據支撐的決策依據：沒有放諸四海皆準的最優方法，"
          "最優選擇是資源、精度與強健性三者在特定應用約束下的權衡結果。同時，公平比較的過程本身"
          "帶出了比排名更深一層的教訓——**演算法的精度上限往往不由演算法決定**：量測鏈的刻度"
          "一致性、參數辨識域與部署域的一致性，這些「環境項」在實測中對誤差的貢獻，數倍於演算法"
          "之間的差距。期望本研究之平台、框架、決策表與此一教訓，能為嵌入式 BMS 之 SOC 演算法"
          "選型提供一份誠實而可操作的參考。")

    d.save(P_)
    print("[done] 第六章已同步")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""sync_ch5_docx_20260707.py — 第五章實測進版同步（就地改 _20260707.docx）。

沿用 sync_ch4_docx_20260707 之渲染函式（**粗體**、X_y 下標）。
"""

import copy
import sys

sys.path.insert(0, "SCRIPTS")
from sync_ch4_docx_20260707 import set_p, insert_after, set_cell  # noqa: E402

import docx  # noqa: E402
from docx.table import Table  # noqa: E402
from docx.text.paragraph import Paragraph  # noqa: E402
from docx.oxml.ns import qn  # noqa: E402

P_ = "DOC/論文撰寫/鋰電池SOC估測方法之比較與嵌入式實作_20260707.docx"


def main():
    d = docx.Document(P_)

    ch5, in5 = [], False
    for el in d.element.body:
        if el.tag == qn("w:p"):
            p = Paragraph(el, d)
            t = p.text.strip()
            if p.style.name == "Heading 1":
                in5 = t.startswith("第五章")
            if in5:
                ch5.append(p)

    def P(prefix):
        for p in ch5:
            if p.text.strip().startswith(prefix):
                return p
        sys.exit(f"找不到段落: {prefix}")

    def T(*heads):
        for tb in d.tables:
            h = [c.text.strip() for c in tb.rows[0].cells]
            if all(any(x.startswith(w) for x in h) for w in heads):
                return tb
        sys.exit(f"找不到表格: {heads}")

    # ---- 5.1 可加性實證 ----
    set_p(P("此架構的關鍵優點是邊際成本可加性"),
          "此架構的關鍵優點是**邊際成本可加性**：由於三法共用前端、僅估測核心分離，三法並行的"
          "總資源佔用以三者各自 footprint（第四章表 4-6）之和為上界。此可加性已由五變體差分"
          "量測**實證**：全方法並行版本實測淨增 Flash +4,936 B、RAM +112 B——RAM 恰等於三法"
          "各自淨增之和（24 + 40 + 48 = 112 B，嚴格可加）；Flash 低於線性和（1,892 + 2,336 "
          "+ 1,540 = 5,768 B）約 14%，因軟體浮點程式庫與命令介面等共用碼於並行版本只鏈結一次。"
          "故「以各法差分之和推估並行上界」成立且略為保守，可直接作為目標微控制器選型依據。")

    # ---- 5.2 ----
    set_p(P("負載分配驗證方法：以實際計時"),
          "**排程設計與驗證方法**：本平台之 100 µs tick 中斷服務常式只遞增節拍計數器（數個 "
          "cycle），估測更新則於主迴圈中在每秒邊界觸發——即估測運算天然跨 tick 攤提、且隨時"
          "可被 tick 中斷搶佔，不存在「單一 tick 超時」問題；需驗證的是估測更新佔每秒運算預算"
          "的比例。驗證資料為 Round 40 整輪 70,802 次更新之 perf_cyc 逐次計時統計"
          "（第四章表 4-6 同源）：")

    tb1 = T("工作項目", "觸發週期")
    hdr1 = ["工作項目", "觸發週期", "單次 CPU cycles（中位／最壞）",
            "佔每秒預算比例（中位／最壞）", "備註"]
    for j, h in enumerate(hdr1):
        set_cell(tb1.rows[0].cells[j], h)
    data1 = [
        ["庫倫計數更新", "1 s", "305 ／ 1,140", "0.0005% ／ 0.0018%", "一乘一加，資源下界"],
        ["EKF 更新", "1 s", "15,187 ／ 17,865", "0.024% ／ 0.028%", "軟浮點，最耗時"],
        ["動態阻抗（無事件）", "1 s", "432 ／ 1,484", "0.0007% ／ 0.0023%", "庫倫內插路徑"],
        ["動態阻抗（有事件）", "擾動事件（~60 s）", "3,117 ／ 6,370", "0.005% ／ 0.010%",
         "差分＋開根＋二次反解"],
        ["三法並行峰值", "1 s 邊界（含事件秒）", "≈18,600 ／ ≈25,400", "0.029% ／ 0.040%",
         "折合約 291 µs（3 個 tick 週期之運算量）"],
    ]
    for i, row in enumerate(data1, start=1):
        for j, v in enumerate(row):
            set_cell(tb1.rows[i].cells[j], v)

    set_p(P("表 5-1　100 µs 系統節拍內之 CPU 負載分配"),
          "表 5-1　CPU 負載分配實測（STM32G071 @64 MHz；每秒預算 64×10⁶ cycles；"
          "「最壞」為整輪觀測最大值，含中斷干擾）")

    set_p(P("預期結論為：三法（含並行）"),
          "實測結論：三法估測更新即使集中於同一秒邊界且該秒恰有擾動事件，總運算量中位僅約 "
          "18,600 cycles（折合 291 µs、佔每秒預算 0.029%），最壞情形亦僅 0.040%——**即時性"
          "餘裕超過三個數量級**。EKF 之軟浮點負擔雖為庫倫計數之約 50 倍，但在每秒一次的更新率"
          "下對 CPU 餘裕的影響可忽略。此即第四章 4.4.3 之結論在系統層級的驗證：「以較高單次"
          "運算量換取精度與強健性」在本級微控制器上不構成即時性代價，資源論述的真正分水嶺在 "
          "Flash 空間與更低階（如 8-bit）平台。")

    # ---- 5.3 ----
    set_p(P("本節以跨輪測試協定（第三章 3.6 節）"),
          "本節以跨輪測試協定（第三章 3.6 節）累積之週期紀錄，回答兩個對全研究結論至關重要的"
          "問題：**(a) 測試平台的輪間再現性有多好？** 此決定第四章所有「以庫倫容量為真值」之"
          "比較是否站得住腳。**(b) 觀測到的容量變化中，有多少是真實老化、有多少是量測噪聲？** "
          "此決定第四章 4.1.4 所述漂移討論的定量基礎。資料涵蓋 rounds 1–40（cycles 1–188，"
          "2026-05-12 至 07-07；round 39 因人為中止未完成 0.5C cycle，不列入趨勢）。")

    set_p(P("以 0.5C 放電容量保持率"),
          "以 0.5C 放電容量保持率（相對實測基準 1665 mAh）逐輪追蹤 40 輪之趨勢，摘要如表 5-3。")

    tb3 = T("階段", "Round", "日期")
    data3 = [["初始", "1", "2026-05-12", "100.76%", "1677.6"],
             ["早期穩定", "11", "2026-05-22", "99.30%", "1653.4"],
             ["中期", "23", "2026-06-02", "98.27%", "1636.3"],
             ["後期", "34", "2026-06-14", "97.45%", "1622.5"],
             ["後期", "38", "2026-06-19", "97.03%", "1615.5"],
             ["最新", "40", "2026-07-07", "96.07%", "1599.6"]]
    while len(tb3.rows) < 1 + len(data3):
        tb3._tbl.append(copy.deepcopy(tb3.rows[-1]._tr))
    for i, row in enumerate(data3, start=1):
        for j, v in enumerate(row):
            set_cell(tb3.rows[i].cells[j], v)

    set_p(P("表 5-3　0.5C 放電容量保持率之長期趨勢"),
          "表 5-3　0.5C 放電容量保持率之長期趨勢（rounds 1–40 實測，摘錄關鍵輪次）")

    set_p(P("自 round 1 至 round 38"),
          "自 round 1 至 round 40，0.5C 容量保持率自 100.76% 緩降至 96.07%，**累計衰退約 "
          "4.7%**，呈大致單調的緩降趨勢（中段偶有 ±0.5% 的輪間起伏，落在 5.3.1 之噪聲帶內；"
          "round 38 → 40 之 1% 落差含約三週的日曆時間與 GITT 深循環之貢獻）。")

    set_p(P("老化與噪聲之分離"),
          "**老化與噪聲之分離**：將 5.3.1 之噪聲下界（CV < 0.52%）與 5.3.2 之長期衰退"
          "（~4.7%）並置，可得一明確結論——**長期衰退幅度（4.7%）顯著大於量測噪聲"
          "（< 0.52%），兩者相差約 9 倍**，故所觀測到的容量緩降為**真實老化訊號**，而非量測"
          "再現性誤差所致。此分離正當化了第四章 4.1.4 對「庫倫容量真值之漂移侷限」的處理方式："
          "在**單一 cycle 內**以實測 q_full 正規化的庫倫 SOC 為可信真值（cycle 內無顯著"
          "老化），而跨 cycle 的容量變化則需如本節以三輪 baseline 之 CV 為基準逐輪扣除噪聲"
          "後解讀。")

    set_p(P("此結果亦為第六章 future work"),
          "此結果亦為第六章 future work 之 SOH 估測提供了實證基礎：本電池在受控深循環下已展現"
          "可量測、可分離的老化軌跡（40 輪約 4.7%），是 SOH 演算法（如容量衰退追蹤、內阻成長法）"
          "日後驗證的天然資料集。")

    # ---- 5.4 新增兩則教訓 ----
    p474 = P("估測涵蓋範圍的一致性")
    pa = insert_after(p474,
          "**激勵時序不可隱含依賴命令延遲**：擾動 dwell 之設定值原為 1 s，但實測發現板端能"
          "穩定抓到 dwell 樣本，係因儀器命令（設定電流、恢復電流）本身各有約 0.5–1 s 的通訊"
          "延遲，實際低電流期長達 2–3 s——時序正確性建立在一個未被設計、隨環境變動的副作用"
          "之上。**教訓**：激勵時序必須顯式參數化（本平台已將 dwell 明訂為 3 s），並以"
          "「部署端取樣率」為約束設計（dwell 遠大於取樣週期，保證至少兩筆穩定樣本），不可讓"
          "正確性依賴命令延遲這類隱含行為。")
    insert_after(pa,
          "**關鍵產出應逐步落盤**：GITT 量測之最終彙總表原設計於整段協定正常結束時一次寫出；"
          "當末步觸及化學下限安全中止時，彙總表即未產出。所幸逐步紀錄（每步一列、即時 flush）"
          "完整落盤，得以離線重建全部結果。**教訓**：長時（>10 小時）自動化測試之關鍵產出必須"
          "隨步驟即時落盤，「只在正常結束時寫檔」等同假設測試永不中斷——而安全中止在電池測試"
          "中是預期會發生的正常結束方式之一。")

    set_p(P("上述案例可歸納為兩條"),
          "上述案例可歸納為三條對嵌入式量測平台普適的設計原則：(1) **不信任單點、不信任單次**"
          "——所有狀態判斷應有時間維度與多樣本佐證；(2) **量測目的與激勵目的須在設計階段就釐清"
          "涵蓋範圍**——避免為其一犧牲其二而不自知；(3) **不讓正確性依賴隱含行為**——時序、"
          "產出、狀態轉移均應顯式設計，任何「剛好能動」都要追問是靠什麼在動。這些原則雖源於本"
          "平台之具體踩坑，但構成了第三章所述平台「高再現性」（5.3.1 之 CV < 0.52%）背後的實作"
          "基礎；而第四章 4.3.4 之量測域發現（參數必須與部署量測鏈同域）可視為原則 (2) 在"
          "「建表域 vs 部署域」層面的再現。")

    # ---- 5.5 ----
    set_p(P("本章自系統層級檢驗"),
          "本章自系統層級檢驗了整個研究的整合與性能。**整合策略**上，提出「共用前端、分離估測、"
          "統一輸出」之三法並行架構，並以五變體差分實測證明其邊際成本可加性——RAM 嚴格可加"
          "（112 B）、Flash 因共用碼低於線性和約 14%，「以各法差分之和推估並行上界」成立且略為"
          "保守。**即時性**上，以 Round 40 整輪 70,802 次更新之實測統計證明：三法並行峰值"
          "（含事件秒）之運算量中位僅約 18,600 cycles（291 µs、佔每秒預算 0.029%），即時性餘裕"
          "超過三個數量級，「EKF 太重」在本級微控制器上不成立。**長期再現性**上，以 rounds "
          "1–40 實測數據證明：本平台 fresh-cell 三輪變異係數 CV < 0.52%，而 40 輪累計容量衰退"
          "約 4.7%，後者顯著大於前者約 9 倍，故老化訊號與量測噪聲可被乾淨分離——此既支撐了"
          "第四章「逐 cycle 重新錨定庫倫真值」之正當性，亦為第六章 SOH 延伸提供了實證基礎。"
          "**工程教訓**上，彙整裸機即時系統之時序陷阱與長時自動化測試之失敗案例，歸納出"
          "「不信任單點、量測涵蓋須在設計階段釐清、不讓正確性依賴隱含行為」三條普適原則。"
          "第六章將在全研究結論之上，給出 SOC 方法選用之決策表、研究限制與未來工作。")

    # 5.4.1 dwell 敘述微調（dwell 1 s → dwell）
    p_cov = P("估測涵蓋範圍的一致性")
    for r in p_cov.runs:
        if "dwell 1 s" in r.text:
            r.text = r.text.replace("dwell 1 s", "dwell")

    d.save(P_)
    print("[done] 第五章已同步")


if __name__ == "__main__":
    main()
